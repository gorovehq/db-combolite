# Compiles the Vulkan accelerator's compute shaders (accel/vulkan/shaders)
# to SPIR-V with glslc and writes them as C arrays, accel/vulkan/cav_spirv.h
# and cav_spirv.c, so a build needs no shader compiler (spec 18.5).
#
#   python3 tools/gen_spirv.py           writes the two files
#   python3 tools/gen_spirv.py --check   checks the checked-in files
#
# The output records a SHA-256 of every shader source and the glslc that
# made it. --check fails when the sources changed since; with that same
# glslc installed, it also regenerates and compares the files byte for
# byte (another glslc version may emit other, equally valid, words).
import hashlib
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ACCEL = os.path.join(HERE, "..", "accel", "vulkan")
SHADERS = os.path.join(ACCEL, "shaders")
OUT_H = os.path.join(ACCEL, "cav_spirv.h")
OUT_C = os.path.join(ACCEL, "cav_spirv.c")


def sources():
    return sorted(f for f in os.listdir(SHADERS) if f.endswith((".comp", ".glsl")))


def digest():
    h = hashlib.sha256()
    for name in sources():
        with open(os.path.join(SHADERS, name), "rb") as f:
            data = f.read()
        h.update(name.encode() + b"\0" + str(len(data)).encode() + b"\0" + data)
    return h.hexdigest()


def glslc_version():
    try:
        out = subprocess.run(["glslc", "--version"], capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    return out.splitlines()[0].strip()


def compile_words(path):
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, "out.spv")
        subprocess.run(["glslc", "--target-env=vulkan1.2", "-O", "-o", spv, path], check=True)
        with open(spv, "rb") as f:
            data = f.read()
    if len(data) % 4 or struct.unpack_from("<I", data)[0] != 0x07230203:
        sys.exit("%s: not SPIR-V" % path)
    return struct.unpack("<%dI" % (len(data) // 4), data)


def generate(version):
    shaders = [f for f in sources() if f.endswith(".comp")]
    names = [os.path.splitext(f)[0] for f in shaders]
    head = ("/* The Vulkan accelerator's compute shaders as SPIR-V (spec 18.5).\n"
            " * Generated by tools/gen_spirv.py from accel/vulkan/shaders; do not edit.\n"
            " * glslc: %s\n"
            " * sources sha256: %s */\n" % (version, digest()))
    h = [head,
         "#ifndef CAV_SPIRV_H\n#define CAV_SPIRV_H\n\n#include <stddef.h>\n#include <stdint.h>\n\n",
         "enum {\n"]
    h += ["    CAV_%s,\n" % n.upper() for n in names]
    h += ["    CAV_SHADER_COUNT\n};\n\n",
          "typedef struct cav_shader {\n    const char *name;\n    const uint32_t *code;\n"
          "    size_t size; /* bytes */\n} cav_shader;\n\n",
          "extern const cav_shader cav_shaders[CAV_SHADER_COUNT];\n\n#endif\n"]
    c = [head, '#include "cav_spirv.h"\n']
    for f, n in zip(shaders, names):
        words = compile_words(os.path.join(SHADERS, f))
        c.append("\nstatic const uint32_t spv_%s[%d] = {\n" % (n, len(words)))
        for i in range(0, len(words), 6):
            c.append("    " + ", ".join("0x%08Xu" % w for w in words[i:i + 6]) + ",\n")
        c.append("};\n")
    c.append("\nconst cav_shader cav_shaders[CAV_SHADER_COUNT] = {\n")
    c += ['    { "%s", spv_%s, sizeof spv_%s },\n' % (n, n, n) for n in names]
    c.append("};\n")
    return "".join(h), "".join(c)


def recorded():
    with open(OUT_C) as f:
        lines = f.read().splitlines()[:4]
    version = lines[2].split("glslc: ", 1)[1]
    sha = lines[3].split("sources sha256: ", 1)[1].split()[0]
    return version, sha


def main():
    version = glslc_version()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        rec_version, rec_sha = recorded()
        if rec_sha != digest():
            sys.exit("cav_spirv.c is out of date: the shader sources changed; run tools/gen_spirv.py")
        if version != rec_version:
            print("sources match; glslc here is %s, not %s, so the words were not compared"
                  % (version, rec_version))
            return
        want_h, want_c = generate(version)
        with open(OUT_H) as f:
            have_h = f.read()
        with open(OUT_C) as f:
            have_c = f.read()
        if have_h != want_h or have_c != want_c:
            sys.exit("cav_spirv.h or cav_spirv.c differs from what glslc makes; run tools/gen_spirv.py")
        print("cav_spirv.h and cav_spirv.c match the sources")
        return
    if version is None:
        sys.exit("glslc not found")
    out_h, out_c = generate(version)
    with open(OUT_H, "w") as f:
        f.write(out_h)
    with open(OUT_C, "w") as f:
        f.write(out_c)


main()
