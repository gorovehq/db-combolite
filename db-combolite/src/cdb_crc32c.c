/* CRC-32C (reflected polynomial 0x82F63B78). The CPU's CRC-32C instruction
 * is used when there is one: x86-64 SSE4.2, found at run time, or ARMv8
 * CRC when the compiler targets it. Otherwise portable slicing-by-8 takes
 * eight bytes per step from eight tables. Every path gives the same value. */
#include <string.h>

#include "cdb_crc32c.h"
#include "cdb_crc32c_table.h"

#if defined(__x86_64__) && (defined(__GNUC__) || defined(__clang__))
#define CDB_CRC32C_X86
#include <nmmintrin.h>
#elif defined(__aarch64__) && defined(__ARM_FEATURE_CRC32) && defined(__BYTE_ORDER__)
#if __BYTE_ORDER__ == __ORDER_LITTLE_ENDIAN__
#define CDB_CRC32C_ARM
#include <arm_acle.h>
#endif
#endif

/* The CRC register is kept inverted between calls (~ on the way in and
 * out), so cdb_crc32c_update can continue a CRC across buffers. The tables
 * (cdb_crc32c_table.h) are generated by a tool in tools/. */
uint32_t cdb_crc32c_sw(uint32_t crc, const void *data, size_t len)
{
    const uint8_t *p = (const uint8_t *)data;
    uint32_t c = ~crc;

    /* Bytes are combined explicitly, so the host's byte order and the
     * buffer's alignment don't matter. */
    while (len >= 8) {
        uint32_t lo = c ^ ((uint32_t)p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24);
        uint32_t hi = (uint32_t)p[4] | (uint32_t)p[5] << 8 | (uint32_t)p[6] << 16 | (uint32_t)p[7] << 24;
        c = crc32c_table[7][lo & 0xFFu] ^ crc32c_table[6][(lo >> 8) & 0xFFu] ^ crc32c_table[5][(lo >> 16) & 0xFFu]
            ^ crc32c_table[4][lo >> 24] ^ crc32c_table[3][hi & 0xFFu] ^ crc32c_table[2][(hi >> 8) & 0xFFu]
            ^ crc32c_table[1][(hi >> 16) & 0xFFu] ^ crc32c_table[0][hi >> 24];
        p += 8;
        len -= 8;
    }
    /* The last 0-7 bytes one at a time. */
    while (len--)
        c = crc32c_table[0][(c ^ *p++) & 0xFFu] ^ (c >> 8);
    return ~c;
}

#ifdef CDB_CRC32C_X86
/* The instruction reads eight bytes as a little-endian word, which is how
 * x86 loads them. */
__attribute__((target("sse4.2"))) static uint32_t crc32c_x86(uint32_t crc, const uint8_t *p, size_t len)
{
    uint64_t c = ~crc;
    uint32_t c32;
    while (len >= 8) {
        uint64_t v;
        memcpy(&v, p, sizeof v);
        c = _mm_crc32_u64(c, v);
        p += 8;
        len -= 8;
    }
    c32 = (uint32_t)c;
    while (len--)
        c32 = _mm_crc32_u8(c32, *p++);
    return ~c32;
}
#endif

#ifdef CDB_CRC32C_ARM
/* Little-endian AArch64 only, for the same reason as x86. */
static uint32_t crc32c_arm(uint32_t crc, const uint8_t *p, size_t len)
{
    uint32_t c = ~crc;
    while (len >= 8) {
        uint64_t v;
        memcpy(&v, p, sizeof v);
        c = __crc32cd(c, v);
        p += 8;
        len -= 8;
    }
    while (len--)
        c = __crc32cb(c, *p++);
    return ~c;
}
#endif

int cdb_crc32c_hw(void)
{
#if defined(CDB_CRC32C_X86)
    return __builtin_cpu_supports("sse4.2") ? 1 : 0;
#elif defined(CDB_CRC32C_ARM)
    return 1;
#else
    return 0;
#endif
}

uint32_t cdb_crc32c_update(uint32_t crc, const void *data, size_t len)
{
#if defined(CDB_CRC32C_X86)
    if (__builtin_cpu_supports("sse4.2"))
        return crc32c_x86(crc, (const uint8_t *)data, len);
#elif defined(CDB_CRC32C_ARM)
    return crc32c_arm(crc, (const uint8_t *)data, len);
#endif
    return cdb_crc32c_sw(crc, data, len);
}
